import sys
import time

import build_manifest as manifest
import toolchain
from verify_builds import integrated_resources, no_test_harnesses, packed_paths, require


def digest(path, algorithm="sha256"):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, algorithm).hexdigest()


def group_state(group):
    result = subprocess.run(["ps", "-axo", "pid=,pgid=,stat="], capture_output=True,
                            text=True, timeout=3, check=True)
    return [line.strip() for line in result.stdout.splitlines()
            if len(line.split()) == 3 and line.split()[1] == str(group)]


def live_group(rows):
    # An orphaned zombie cannot execute; retain it in the raw cleanup receipt.
    return [row for row in rows if not row.split()[2].startswith("Z")]


def bounded_command(command, log, seconds, *, env=None):
    """File-backed output, a new owned group, and cleanup even after leader exit."""
    require(seconds > 0, "Total command deadline exhausted")
    started = time.monotonic()
    record = {"command": [str(item) for item in command], "timeout_seconds": seconds,
              "timed_out": False, "exit_code": None, "cleanup_errors": []}
    with Path(log).open("w", encoding="utf-8") as stream:
        process = subprocess.Popen(command, stdout=stream, stderr=subprocess.STDOUT,
                                   env=env, start_new_session=True)
        record["owned_process_group"] = process.pid
        try:
            try:
                process.wait(timeout=seconds)
            except subprocess.TimeoutExpired:
                record["timed_out"] = True
        finally:
            # Do not rely on process.poll(): compiler descendants may outlive it.
            try:
                rows = group_state(process.pid)
                record["group_before_cleanup"] = rows
                record["unexpected_descendants"] = bool(live_group(rows)) and not record["timed_out"]
            except (OSError, subprocess.SubprocessError) as error:
                record["cleanup_errors"].append(str(error))
                rows = ["unknown"]
            if rows:
                for sig in (signal.SIGTERM, signal.SIGKILL):
                    try:
                        os.killpg(process.pid, sig)
                    except ProcessLookupError:
                        pass
                    except OSError as error:
                        record["cleanup_errors"].append(str(error))
                    try:
                        process.wait(timeout=2)
                    except subprocess.TimeoutExpired:
                        continue
            try:
                process.wait(timeout=2)
            except subprocess.TimeoutExpired:
                record["cleanup_errors"].append("Owned command leader did not exit")
            try:
                record["group_after_cleanup"] = group_state(process.pid)
                record["surviving_owned_processes"] = live_group(record["group_after_cleanup"])
            except (OSError, subprocess.SubprocessError) as error:
                record["cleanup_errors"].append(str(error))
                record["surviving_owned_processes"] = ["unknown"]
            record.update(exit_code=process.poll(), seconds=time.monotonic() - started,
                          log=Path(log).name)
    record["cleanup_complete"] = not record["cleanup_errors"] and not record["surviving_owned_processes"]
    return record


def inspect_macho(path):
    """Require a thin, unsigned arm64 device-iOS executable, not a simulator."""
    with Path(path).open("rb") as stream:
        header = stream.read(32)
        require(len(header) == 32 and header[:4] == b"\xcf\xfa\xed\xfe", "Expected thin 64-bit Mach-O")
        _, cpu, _, kind, count, size, _, _ = struct.unpack("<8I", header)
        require(cpu == 0x0100000C and kind == 2, "Expected arm64 MH_EXECUTE")
        require(size <= 16 * 1024 * 1024, "Oversized Mach-O command table")
        commands = stream.read(size)
    require(len(commands) == size, "Truncated Mach-O load commands")
    offset, platforms = 0, []
    for _ in range(count):
        require(offset + 8 <= size, "Truncated Mach-O command")
        command, length = struct.unpack_from("<II", commands, offset)
        require(length >= 8 and offset + length <= size, "Invalid Mach-O command length")
        require(command != 0x1D, "Code signature present in executable")
        if command == 0x32:  # LC_BUILD_VERSION, generated by the current Apple linker.
            require(length >= 24, "Invalid platform command")
            platforms.append(struct.unpack_from("<I", commands, offset + 8)[0])
        offset += length
    require(offset == size and platforms == [2], "Expected one device-iOS build platform (2)")
    return {"architecture": "arm64", "format": "Mach-O MH_EXECUTE", "platform": "iOS device",
            "code_signature_load_command": False, "bytes": Path(path).stat().st_size,
            "sha256": digest(path)}


def inspect_app(app, export, source_record):
    require(app.is_dir() and not app.is_symlink(), "Missing fresh compiled app")
    require(not any(p.name in ("_CodeSignature", "embedded.mobileprovision") for p in app.rglob("*")),
            "Signature or provisioning profile found in app")
    with (app / "Info.plist").open("rb") as stream:
        info = plistlib.load(stream)
    require(info["CFBundleIdentifier"] == "com.sightbreak.game", "Wrong compiled bundle ID")
    require(info["CFBundleShortVersionString"] == manifest.IOS_VERSION and
            str(info["CFBundleVersion"]) == str(manifest.BUILD_NUMBER), "Wrong compiled app version")
    require(info.get("DTPlatformName") == "iphoneos" and info.get("CFBundleSupportedPlatforms") == ["iPhoneOS"],
            "Compiled app is not an iPhoneOS device product")
    executable_name = info["CFBundleExecutable"]
    require(executable_name == "sightbreak", "Unexpected app executable")
    executable = app / executable_name
    require(not executable.is_symlink(), "Symlinked app executable")
    binary = inspect_macho(executable)
    packs = list(app.rglob("*.pck"))
    require(packs == [app / "sightbreak.pck"] and not packs[0].is_symlink(), "Missing, duplicate or symlinked app PCK")
    expected = [item for item in source_record["payload"] if item["path"] == "ios/sightbreak.pck"]
    require(len(expected) == 1, "Missing exact exported PCK provenance")
    pack = export / "ios/sightbreak.pck"
    require(not pack.is_symlink() and pack.stat().st_size > 0, "Invalid exported PCK")
    require(digest(pack) == expected[0]["sha256"] and pack.stat().st_size == expected[0]["bytes"],
            "Exported PCK changed from source manifest")
    require(digest(packs[0]) == expected[0]["sha256"] and packs[0].stat().st_size == expected[0]["bytes"],
            "Compiled app PCK differs from exact exported source")
    paths = packed_paths(packs[0])
    no_test_harnesses(paths)
    integrated_resources(paths)
    return {"executable": binary, "bundle_id": info["CFBundleIdentifier"],
            "pck_sha256": expected[0]["sha256"], "pck_resources": len(paths),
            "signature_directory": False, "embedded_profile": False}


def compile_command(export, derived):
    return ["xcodebuild", "-project", str(export / "ios/sightbreak.xcodeproj"),
            "-scheme", "sightbreak", "-configuration", "Debug", "-sdk", "iphoneos",
            "-destination", "generic/platform=iOS", "-derivedDataPath", str(derived),
            "CODE_SIGNING_ALLOWED=NO", "build"]


def qualify(output, export, derived, seconds):
    require(0 < seconds <= 1200, "Choose a total command budget between 1 and 1200 seconds")
    for path in (output, export, derived):
        require(not path.exists(), "Preserve earlier attempt; use fresh output paths: " + str(path))
    require(len({output, export, derived}) == 3 and
            not any(a.is_relative_to(b) for a in (output, export, derived) for b in (output, export, derived) if a != b),
            "Keep receipts, export and DerivedData in separate directories")
    output.mkdir(parents=True)
    started = time.monotonic()
    deadline = started + seconds
    report = {"schema": 1, "compile_completed": False, "status": "FAILED",
              "scope": "Unsigned generic-device Debug compile only; no installation or runtime qualification.",
              "simulator": "UNVERIFIED; upstream debug simulator archive architecture mismatch remains separate.",
              "physical_device": "UNVERIFIED", "total_command_budget_seconds": seconds, "commands": []}
    environment = dict(os.environ, SIGHTBREAK_BUILDS_DIR=str(export))

    def run(label, command, limit=30, expected=(0,)):
        result = bounded_command(command, output / (label + ".log"),
                                 min(limit, deadline - time.monotonic()), env=environment)
        report["commands"].append({"label": label, **result})
        manifest.write_json(output / "compile.json", report)
        require(result["cleanup_complete"] and not result.get("unexpected_descendants"), "Owned process cleanup failed: " + label)
        require(not result["timed_out"] and result["exit_code"] in expected, "Command failed: " + label)
        return (output / (label + ".log")).read_text(encoding="utf-8", errors="replace")

    try:
        report["host"] = {"system": platform.system(), "machine": platform.machine(), "platform": platform.platform()}
        require(platform.system() == "Darwin" and platform.machine() == "arm64", "Requires native ARM macOS; no test skip")
        snapshot_command = [sys.executable, str(Path(__file__).resolve()), "--source-snapshot"]
        # Bound local git/hash provenance work in the same owned-process wrapper.
        report["source"] = json.loads(run("source-before", snapshot_command))
        report["xcode_version"] = run("xcode-version", ["xcodebuild", "-version"]).strip()
        require(report["xcode_version"].startswith("Xcode "), "Native Xcode identity missing")
        report["developer_directory"] = run("xcode-select", ["xcode-select", "-p"]).strip()
        report["iphoneos_sdk"] = run("iphoneos-sdk", ["xcrun", "--sdk", "iphoneos", "--show-sdk-path"]).strip()
        report["iphoneos_sdk_version"] = run("iphoneos-sdk-version", ["xcrun", "--sdk", "iphoneos", "--show-sdk-version"]).strip()
        report["clang_version"] = run("clang-version", ["xcrun", "--sdk", "iphoneos", "clang", "--version"]).strip()
        require("Apple clang" in report["clang_version"], "Apple compiler identity missing")
        archive = toolchain.INSTALL / "templates.tpz"
        require(archive.is_file(), "Pinned templates must already be cached by native setup")
        report["templates_sha512"] = digest(archive, "sha512")
        require(report["templates_sha512"] == toolchain.TEMPLATES_SHA512, "Cached template checksum mismatch")
        run("install-ios-template", [sys.executable, str(manifest.ROOT / "scripts/toolchain.py"), "setup", "--targets", "ios"], 180)
        report["engine"] = toolchain.ENGINE
        run("export-command", [sys.executable, str(manifest.ROOT / "scripts/export.py"), "ios"], 420)
        run("inspect-project", [sys.executable, str(manifest.ROOT / "scripts/verify_builds.py"), "--targets", "ios"], 60)
        # The parent process's manifest constant is untouched; all export library
        # validation runs in children with the new SIGHTBREAK_BUILDS_DIR.
        source_record = json.loads((export / "ios/source.json").read_text())
        require(manifest.same_source(source_record, report["source"]) and source_record["export_completed"], "Wrong export provenance")
        build_log = run("xcodebuild-device", compile_command(export, derived), 600)
        require("** BUILD SUCCEEDED **" in build_log and
                re.search(r"(?m)^(CompileC|SwiftCompile) ", build_log) and re.search(r"(?m)^Ld .* normal arm64", build_log),
                "Compiler, linker or build-success evidence missing")
        app = derived / "Build/Products/Debug-iphoneos/sightbreak.app"
        report["app"] = inspect_app(app, export, source_record)
        signature = run("unsigned-app", ["codesign", "-d", "--verbose=4", str(app)], expected=(1,))
        require("code object is not signed at all" in signature, "codesign did not establish unsigned app")
        run("inspect-project-after-build", [sys.executable, str(manifest.ROOT / "scripts/verify_builds.py"), "--targets", "ios"], 60)
        require(json.loads(run("source-after", snapshot_command)) == report["source"], "Source changed during iOS qualification")
        report.update(status="PASS", compile_completed=True)
    except (Exception, SystemExit) as error:
        report["failure"] = str(error)
    finally:
        # Copy only evidence files; frameworks, archives, PCK and app stay out of QA.
        for relative, name in (("ios/source.json", "exported-source.json"),
                               ("ios/import.log", "export-import.log"), ("ios/export.log", "export-export.log"),
                               ("verification/results.json", "project-inspection.json")):
            path = export / relative
            if path.is_file():
                shutil.copy2(path, output / name)
        report["seconds"] = time.monotonic() - started
        manifest.write_json(output / "compile.json", report)
    print(json.dumps(report, indent=2))
    return 0 if report["compile_completed"] else 1


def main():
    if sys.argv[1:] == ["--source-snapshot"]:
        current = manifest.source()
        manifest.clean(current)
        print(json.dumps(current))
        return 0
    def interrupted(signum, _frame):
        # GitHub cancellation must unwind the owned command's finally block.
        raise SystemExit("Interrupted by signal " + str(signum))
    signal.signal(signal.SIGTERM, interrupted)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--builds", type=Path, required=True)
    parser.add_argument("--derived-data", type=Path, required=True)
    parser.add_argument("--timeout", type=float, default=900)
    args = parser.parse_args()
    return qualify(args.output.resolve(), args.builds.resolve(), args.derived_data.resolve(), args.timeout)


if __name__ == "__main__":
    raise SystemExit(main())
