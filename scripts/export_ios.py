#!/usr/bin/env python3
"""Export an unsigned Xcode project without changing the checkout's signing settings."""
import os
import pathlib
import re
import shutil
import subprocess
import tempfile

from build_manifest import ROOT, begin, finish

state = pathlib.Path(os.environ.get("SIGHTBREAK_STATE_DIR", ROOT / ".local")).resolve()
tools = pathlib.Path(os.environ.get("SIGHTBREAK_TOOLS_DIR", ROOT.parent / "tools")).resolve()
binary = os.environ.get("GODOT_BIN", str(tools / "godot-4.7.2/Godot_v4.7.2-stable_linux.x86_64"))
output = ROOT / "builds/ios"
output.mkdir(parents=True, exist_ok=True)
state.mkdir(parents=True, exist_ok=True)
begin("ios")
environment = dict(os.environ)
for variable, suffix in [("XDG_DATA_HOME", "data"), ("XDG_CONFIG_HOME", "config"), ("XDG_CACHE_HOME", "cache"), ("ANDROID_USER_HOME", "android")]:
    environment[variable] = str(state / suffix)
    (state / suffix).mkdir(parents=True, exist_ok=True)

with tempfile.TemporaryDirectory(prefix="ios-export-", dir=state) as temporary:
    project = pathlib.Path(temporary) / "game"
    shutil.copytree(ROOT / "game", project, ignore=shutil.ignore_patterns(".godot"))
    presets = project / "export_presets.cfg"
    # Godot requires a nonempty team even for project-only exports. The sentinel is
    # stripped from generated files; it is never a real signing identity.
    text = presets.read_text().replace('application/app_store_team_id=""', 'application/app_store_team_id="UNSIGNED00"')
    text = text.replace('application/export_project_only=true', 'application/export_project_only=true\napplication/delete_old_export_files_unconditionally=true')
    presets.write_text(text)
    for label, arguments in [("import", ["--editor", "--import", "--quit"]), ("export", ["--export-debug", "iOS", str(output / "sightbreak.zip")])]:
        result = subprocess.run([binary, "--headless", "--path", str(project), *arguments], env=environment, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        (output / f"{label}.log").write_text(result.stdout)
        if result.returncode or re.search(r"^(?:SCRIPT ERROR|ERROR:)|Parse Error", result.stdout, re.M):
            print(result.stdout)
            raise SystemExit(f"iOS {label} failed; see builds/ios/{label}.log")

for path in output.rglob("*"):
    if path.is_file() and path.suffix in {".pbxproj", ".plist", ".entitlements"}:
        text = path.read_text()
        path.write_text(text.replace("= UNSIGNED00;", '= "";').replace("UNSIGNED00", ""))
for name in ["GODOT-LICENSE.txt", "GODOT-COPYRIGHT.txt"]:
    shutil.copy2(ROOT / "docs" / name, output / name)
(output / "BUILD-ON-MAC.md").write_text("""# SIGHTBREAK unsigned iOS project

Generated by Godot 4.7.2 on Linux. This is an Xcode project, not an IPA.
Open `sightbreak.xcodeproj` in current Xcode on macOS. Select the sightbreak
target, choose your Development Team in Signing & Capabilities, and change
the bundle identifier if necessary. Select an attached iPhone/iPad and Run.
The engine and game PCK are included; Godot is not required to open the project.

For a compile-only check without signing on a Mac:
`xcodebuild -project sightbreak.xcodeproj -scheme sightbreak -configuration Debug -sdk iphoneos -destination 'generic/platform=iOS' CODE_SIGNING_ALLOWED=NO build`

No Apple signing identity or provisioning profile is bundled. macOS compilation,
installation, device performance, touch ergonomics, suspend/resume, and LAN
permission behavior remain to be verified on Apple hardware.
""")
finish("ios")
print(f"Unsigned Xcode project exported: {output / 'sightbreak.xcodeproj'}")
